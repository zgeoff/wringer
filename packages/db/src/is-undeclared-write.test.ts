import { expect, test } from 'bun:test';
import { isUndeclaredWrite } from './is-undeclared-write.ts';

test.each([
  { dialect: 'sqlite', sql: 'select text from notes', write: false },
  { dialect: 'sqlite', sql: "VACUUM INTO '/srv/copy.db'", write: true },
  { dialect: 'sqlite', sql: "vacuum into '/srv/copy.db'", write: true },
  { dialect: 'sqlite', sql: "attach '/srv/other.db' as other", write: true },
  { dialect: 'sqlite', sql: 'pragma query_only = 0', write: true },
  { dialect: 'sqlite', sql: "select 'vacuum' as label", write: false },
  { dialect: 'sqlite', sql: 'select 1 /* attach */', write: false },
  { dialect: 'sqlite', sql: "/* /* */ attach '/srv/other.db' as other", write: true },
  { dialect: 'postgres', sql: 'select id from orders', write: false },
  { dialect: 'postgres', sql: '  -- open orders\n(select id from orders)', write: false },
  { dialect: 'postgres', sql: 'with open as (select 1) select * from open', write: false },
  { dialect: 'postgres', sql: 'delete from orders', write: true },
  { dialect: 'postgres', sql: '-- tidy up\rdelete from orders', write: true },
  { dialect: 'postgres', sql: "COPY (select 1) TO PROGRAM 'touch /srv/flag'", write: true },
  { dialect: 'postgres', sql: "copy orders to '/srv/orders.csv'", write: true },
  { dialect: 'postgres', sql: "select lo_export(16384, '/srv/blob')", write: true },
  { dialect: 'postgres', sql: 'select pg_catalog."lo_export"(16384, \'/srv/blob\')', write: true },
  {
    dialect: 'postgres',
    sql: "do $$ begin execute 'copy (select 1) to program ''touch /srv/flag'''; end $$",
    write: true,
  },
  {
    dialect: 'postgres',
    sql: "DO $$ BEGIN EXECUTE 'CO' || 'PY (select 1) TO PROGRAM ''touch /srv/flag'''; END $$",
    write: true,
  },
  { dialect: 'postgres', sql: 'select 1; /* tidy */ do $$ begin perform 1; end $$', write: true },
  {
    dialect: 'postgres',
    sql: "select \"query_to_xml\"('CO' || 'PY orders TO ''/srv/o.csv''', true, true, '')",
    write: true,
  },
  { dialect: 'postgres', sql: "select dblink_exec('host=db', 'delete from orders')", write: true },
  { dialect: 'postgres', sql: "select 'what to do' as note", write: false },
  { dialect: 'postgres', sql: String.raw`select U&"\006Co_export"(1, 'x')`, write: true },
  { dialect: 'postgres', sql: 'select "copy_count" from orders', write: false },
  { dialect: 'postgres', sql: 'with open as (select 1) delete from orders', write: true },
  {
    dialect: 'postgres',
    sql: "with open as (select 'delete' as word) select * from open",
    write: false,
  },
  { dialect: 'postgres', sql: '/* tidy */ insert into notes values (1)', write: true },
  {
    dialect: 'postgres',
    sql: "/* /* */ ' */ DO $$ BEGIN EXECUTE 'CO' || 'PY (select 1) TO PROGRAM ''touch /srv/flag'''; END $$ -- '",
    write: true,
  },
  { dialect: 'postgres', sql: 'select 1 /* copy the orders */', write: false },
  { dialect: 'postgres', sql: 'select $$ what to do $$ as note', write: false },
  { dialect: 'postgres', sql: 'select 1 /* a /* b */ do', write: true },
  { dialect: 'postgres', sql: "select 'unclosed", write: true },
  {
    dialect: 'postgres',
    sql: 'select pg_terminate_backend(pid) from pg_stat_activity where pid <> pg_backend_pid()',
    write: true,
  },
  { dialect: 'postgres', sql: 'select pg_cancel_backend(pid) from pg_stat_activity', write: true },
  { dialect: 'postgres', sql: "select set_config('statement_timeout', '0', false)", write: true },
  { dialect: 'postgres', sql: 'select pg_sleep(600)', write: true },
  { dialect: 'postgres', sql: 'select "pg_sleep"(600)', write: true },
  { dialect: 'postgres', sql: 'select pg_catalog.pg_reload_conf()', write: true },
  { dialect: 'postgres', sql: 'select pg_advisory_lock(42)', write: true },
  { dialect: 'postgres', sql: "select pg_notify('orders', 'paid')", write: true },
  { dialect: 'postgres', sql: 'select shop.lower(name) from items', write: true },
  { dialect: 'postgres', sql: 'select "Lower"(name) from items', write: true },
  {
    dialect: 'postgres',
    sql: 'with totals(day, amount) as (select 1, 2) select * from totals',
    write: true,
  },
  {
    dialect: 'postgres',
    sql: 'select count(*), pg_catalog.max(total), lower(name) from orders group by lower(name)',
    write: false,
  },
  {
    dialect: 'postgres',
    sql: 'select cast(total as numeric(10, 2)) from orders where id in (select id from paid)',
    write: false,
  },
  {
    dialect: 'postgres',
    sql: 'select row_number() over (partition by day order by total) from orders',
    write: false,
  },
] as const)('it reads `$sql` on $dialect as a write: $write', (row) => {
  expect(isUndeclaredWrite(row.dialect, row.sql)).toBe(row.write);
});

